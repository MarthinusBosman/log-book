import { getDb } from '#lib/server/db/index.ts';
import { SESSION_COOKIE, validateSessionToken } from '#lib/server/auth/session.ts';
import { clearSessionCookie, setSessionCookie } from '#lib/server/auth/cookie.ts';
import { parseTheme, themeClass, THEME_COLORS, THEME_COOKIE, type PageTheme } from '#lib/theme.ts';
import { readBranding } from '#lib/branding.ts';
import { afterMutation } from '#lib/server/import/federation/web.ts';
import { DZ_COOKIE, findDropzoneBySlug } from '#lib/server/dropzones/index.ts';
import { closeStaleCheckins } from '#lib/server/domain/checkins.ts';
import { canonicalRedirect } from '#lib/server/canonical.ts';
import { CANONICAL_HOST } from '$app/env/private';
import { isCsrfForbidden } from '#lib/server/csrf.ts';
import { cacheableMethod } from '#lib/server/request-cache.ts';

/** Cross-site form posts are rejected (Kit's built-in check, minus signed payment webhooks). */
const csrf: Handle = async ({ event, resolve }) => {
	const r = event.request;
	if (
		isCsrfForbidden({
			method: r.method,
			contentType: r.headers.get('content-type'),
			origin: r.headers.get('origin'),
			selfOrigin: event.url.origin,
			pathname: event.url.pathname
		})
	) {
		const message = `Cross-site ${r.method} form submissions are forbidden`;
		if (r.headers.get('accept') === 'application/json') return Response.json({ message }, { status: 403 });
		return new Response(message, { status: 403, headers: { 'content-type': 'text/plain' } });
	}
	return resolve(event);
};

/** log-book.io / www.* → https://log-book.app (only when CANONICAL_HOST is set). */
const canonicalHost: Handle = async ({ event, resolve }) => {
	const to = canonicalRedirect(event.url, event.request.method, CANONICAL_HOST);
	if (to) return new Response(null, { status: to.status, headers: { location: to.location } });
	return resolve(event);
};

const database: Handle = async ({ event, resolve }) => {
	event.locals.db = await getDb();
	if (cacheableMethod(event.request.method)) event.locals.cache = new Map();
	return resolve(event);
};

const auth: Handle = async ({ event, resolve }) => {
	const token = event.cookies.get(SESSION_COOKIE);
	const secure = event.url.protocol === 'https:';
	if (!token) {
		event.locals.user = null;
		event.locals.session = null;
		return resolve(event);
	}
	const { session, user } = await validateSessionToken(event.locals.db, token);
	if (session) {
		// Keep the cookie expiry in step with the sliding DB expiry.
		setSessionCookie(event.cookies, token, session.expiresAt, secure);
	} else {
		clearSessionCookie(event.cookies, secure);
	}
	event.locals.user = user;
	event.locals.session = session;
	return resolve(event);
};

/** A dropzone's default theme applies to its public pages + display for visitors who haven't picked one. */
async function dzDefaultTheme(event: Parameters<Handle>[0]['event']): Promise<PageTheme | null> {
	const m = /^\/dz\/([^/]+)/.exec(event.url.pathname);
	if (!m) return null;
	try {
		const dz = await findDropzoneBySlug(event.locals.db, decodeURIComponent(m[1]));
		return dz ? readBranding(dz.settings).theme : null;
	} catch {
		return null;
	}
}

const theme: Handle = async ({ event, resolve }) => {
	const raw = event.cookies.get(THEME_COOKIE);
	const t: PageTheme = (raw ? null : await dzDefaultTheme(event)) ?? parseTheme(raw);
	event.locals.theme = t;
	return resolve(event, {
		// Preload the Latin Inter subset (the only one most pages need) so text doesn't swap late.
		preload: ({ type, path }) => type === 'js' || type === 'css' || (type === 'font' && path.includes('inter-latin-wght')),
		transformPageChunk: ({ html }) =>
			html
				.replace('%dz.theme%', themeClass(t))
				.replace('%dz.themeColor%', THEME_COLORS[t === 'system' ? 'dark' : t])
	});
};

/** Features the app uses: geolocation ("near me"), clipboard (copy links), Web Share. */
const PERMISSIONS_POLICY = [
	'geolocation=(self)',
	'clipboard-write=(self)',
	'web-share=(self)',
	'camera=()',
	'microphone=()',
	'payment=()',
	'usb=()',
	'serial=()',
	'bluetooth=()'
].join(', ');

/**
 * Security headers for every dynamic response. The CSP for pages is generated by SvelteKit (nonce
 * per request — see `csp` in vite.config.ts); non-HTML responses (APIs, PDFs, images) get a strict
 * fallback so a stored file can never run script in our origin.
 */
const securityHeaders: Handle = async ({ event, resolve }) => {
	const response = await resolve(event);
	const h = response.headers;
	const set = (k: string, v: string) => {
		try {
			h.set(k, v);
		} catch {
			/* immutable headers (e.g. a proxied fetch Response) */
		}
	};
	set('X-Content-Type-Options', 'nosniff');
	set('Referrer-Policy', 'strict-origin-when-cross-origin');
	set('X-Frame-Options', 'SAMEORIGIN');
	set('Permissions-Policy', PERMISSIONS_POLICY);
	set('Cross-Origin-Opener-Policy', 'same-origin');
	if (event.url.protocol === 'https:') set('Strict-Transport-Security', 'max-age=31536000; includeSubDomains');
	const type = h.get('content-type') ?? '';
	// PDFs are left alone: `sandbox`/`object-src 'none'` stop browsers' built-in PDF viewers.
	if (!h.has('content-security-policy') && !type.startsWith('text/html') && !type.startsWith('application/pdf')) {
		set('Content-Security-Policy', "default-src 'none'; frame-ancestors 'self'; sandbox");
	}
	if (event.url.pathname.startsWith('/app')) {
		set('Cache-Control', 'private, no-store');
	}
	return response;
};

/** Federation: push queued logbook entries after mutating requests (e.g. completing a load). */
const federation: Handle = async ({ event, resolve }) => {
	const response = await resolve(event);
	await afterMutation(event);
	return response;
};

/**
 * Day rollover: check-ins left open from a previous day are closed before /app renders, so
 * "checked in" / "on site now" always mean today (the user's own, and the selected dropzone's).
 */
const checkinRollover: Handle = async ({ event, resolve }) => {
	const user = event.locals.user;
	if (user && event.request.method === 'GET' && event.url.pathname.startsWith('/app')) {
		try {
			const slug = event.cookies.get(DZ_COOKIE);
			const dz = slug ? await findDropzoneBySlug(event.locals.db, slug) : null;
			await closeStaleCheckins(event.locals.db, { userId: user.id });
			if (dz) await closeStaleCheckins(event.locals.db, { dropzoneId: dz.id });
		} catch (e) {
			console.error('check-in rollover failed', e);
		}
	}
	return resolve(event);
};

export const handle = sequence(csrf, canonicalHost, securityHeaders, database, auth, checkinRollover, theme, federation);

/**
 * Bun (long-lived server): hourly housekeeping + federation retry, in-process. Cloudflare uses a
 * cron trigger instead (scripts/cf-postbuild.ts → POST /api/cron).
 */
export const init: ServerInit = () => {
	if (__DEPLOY_TARGET__ !== 'bun' || building) return;
	const g = globalThis as { __dzHousekeeping?: ReturnType<typeof setInterval> };
	if (g.__dzHousekeeping) return;
	const run = async () => {
		try {
			const { runScheduled } = await import('#lib/server/housekeeping.ts');
			const result = await runScheduled(await getDb());
			if (result.sessions || result.resetTokens || result.orphanBlobs || result.files?.orphanObjects || result.files?.staleImports || result.files?.legacyPdfs || result.files?.orphanSignatures) console.info('[housekeeping]', JSON.stringify(result));
		} catch (e) {
			console.warn('[housekeeping] failed', e);
		}
	};
	g.__dzHousekeeping = setInterval(run, 60 * 60 * 1000);
	g.__dzHousekeeping.unref?.();
	setTimeout(run, 30_000).unref?.();
};
