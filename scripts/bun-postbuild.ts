/**
 * Runs after `vite build` for the bun target (part of `bun run build:bun`): writes `build/server.js`,
 * the production entry point. It only sets sensible defaults for adapter-node env vars before
 * starting `build/index.js` — adapter-node's BODY_SIZE_LIMIT default (512K) is too small for photo
 * uploads (5 MB), PDFs and logbook imports (10 MB).
 */
import { existsSync, writeFileSync } from "node:fs";

if (!existsSync("build/index.js"))
  throw new Error("build/index.js not found — run the bun build first");
writeFileSync(
  "build/server.js",
  `// Generated by scripts/bun-postbuild.ts — production entry: \`bun build/server.js\`.
// docker compose passes unset optional vars as "" — treat those as unset for adapter-node.
// An empty ORIGIN therefore means "derive the origin per request" from PROTOCOL_HEADER/HOST_HEADER
// (LAN setups reachable under several names: docs/SELF_HOSTING.md → Local-only).
for (const k of ['ORIGIN', 'PROTOCOL_HEADER', 'HOST_HEADER', 'ADDRESS_HEADER', 'PORT_HEADER', 'XFF_DEPTH', 'BODY_SIZE_LIMIT']) {
	if (process.env[k] === '') delete process.env[k];
}
if (!process.env.ORIGIN && !process.env.PROTOCOL_HEADER) {
	console.warn('[server] ORIGIN is not set and no PROTOCOL_HEADER: every request is treated as https. Set ORIGIN (e.g. http://192.168.1.10:3000) or run behind a proxy with PROTOCOL_HEADER=x-forwarded-proto.');
}
// Uploads are capped at 10 MB by the app; leave headroom for multipart overhead.
process.env.BODY_SIZE_LIMIT ||= '12M';
await import('./index.js');
`,
);
console.info(
  "[bun-postbuild] wrote build/server.js (BODY_SIZE_LIMIT default 12M)",
);
